def parse_maxstats(info):
    """
    Parse Max's custom UCI info string
    """

    stats = {
        "main_nodes": None,
        "qnodes": None,
        "tt_probes": None,
        "tt_hits": None,
        "beta_cutoffs": None,
        "q_beta_cutoffs": None,
    }

    text = info.get("string")

    if (
        not text
        or not text.startswith("maxstats ")
    ):
        return stats

    for token in text.split()[1:]:

        if "=" not in token:
            continue

        key, value = token.split(
            "=",
            1
        )

        if key in stats:
            stats[key] = safe_int(value)

    return stats


def score_from_pov(info, color):
    """
    Return Max's search score in centipawns from the requested color's point of view
    """

    score = info.get("score")

    if score is None:
        return None

    return score.pov(color).score(
        mate_score=100000
    )


def tt_hit_rate(tt_hits, tt_probes):
    """Return TT hit rate as a percentage"""

    if (
        tt_hits is None
        or tt_probes is None
        or tt_probes == 0
    ):
        return 0.0

    return (
        100.0
        * tt_hits
        / tt_probes
    )


