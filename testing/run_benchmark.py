def summarize_move_rows(rows):
    """Summarize a collection of Max search-stat rows"""

    if not rows:

        return {
            "max_moves": 0,
            "avg_depth": 0.0,
            "avg_main_nodes": 0.0,
            "avg_qnodes": 0.0,
            "avg_total_nodes": 0.0,
            "qnode_share_pct": 0.0,
            "avg_nps": 0.0,
            "tt_probes": 0,
            "tt_hits": 0,
            "tt_hit_rate_pct": 0.0,
            "avg_beta_cutoffs": 0.0,
            "avg_q_beta_cutoffs": 0.0,
            "avg_reported_time_s": 0.0,
            "avg_wall_time_s": 0.0,
        }

    total_main_nodes = sum(
        row["main_nodes"] or 0
        for row in rows
    )

    total_qnodes = sum(
        row["qnodes"] or 0
        for row in rows
    )

    total_nodes = (
        total_main_nodes
        + total_qnodes
    )

    total_tt_probes = sum(
        row["tt_probes"] or 0
        for row in rows
    )

    total_tt_hits = sum(
        row["tt_hits"] or 0
        for row in rows
    )

    qnode_share_pct = (
        100.0
        * total_qnodes
        / total_nodes
        if total_nodes > 0
        else 0.0
    )

    return {
        "max_moves": len(rows),

        "avg_depth": average(
            [row["depth"] for row in rows]
        ),

        "avg_main_nodes": average(
            [row["main_nodes"] for row in rows]
        ),

        "avg_qnodes": average(
            [row["qnodes"] for row in rows]
        ),

        "avg_total_nodes": average(
            [row["total_nodes"] for row in rows]
        ),

        "qnode_share_pct": qnode_share_pct,

        "avg_nps": average(
            [row["nps"] for row in rows]
        ),

        "tt_probes": total_tt_probes,

        "tt_hits": total_tt_hits,

        "tt_hit_rate_pct": tt_hit_rate(
            total_tt_hits,
            total_tt_probes
        ),

        "avg_beta_cutoffs": average(
            [
                row["beta_cutoffs"]
                for row in rows
            ]
        ),

        "avg_q_beta_cutoffs": average(
            [
                row["q_beta_cutoffs"]
                for row in rows
            ]
        ),

        "avg_reported_time_s": average(
            [
                row["reported_time_s"]
                for row in rows
            ]
        ),

        "avg_wall_time_s": average(
            [
                row["wall_time_s"]
                for row in rows
            ]
        ),
    }


