def average(values):
    """Return the arithmetic mean of all non-None values"""

    clean = [
        value
        for value in values
        if value is not None
    ]

    return (
        sum(clean) / len(clean)
        if clean
        else 0.0
    )


def safe_int(value, default=None):
    try:
        return int(value)
    except (TypeError, ValueError):
        return default


def safe_float(value, default=None):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def initialize_csv(path, fieldnames):
    """Create or overwrite a CSV file and write its header"""

    with open(
        path,
        "w",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames
        )

        writer.writeheader()


def append_csv_row(path, fieldnames, row):
    """Append one row to a CSV file"""

    with open(
        path,
        "a",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=fieldnames
        )

        writer.writerow(row)


def prepare_output_directory():
    """
    Create output folders and remove files generated by previous runs
    """

    os.makedirs(
        OUTPUT_DIR,
        exist_ok=True
    )

    os.makedirs(
        PGN_DIR,
        exist_ok=True
    )

    for filename in os.listdir(PGN_DIR):

        if (
            filename.startswith("game_")
            and filename.endswith(".pgn")
        ):

            os.remove(
                os.path.join(
                    PGN_DIR,
                    filename
                )
            )

    with open(
        MERGED_PGN_PATH,
        "w",
        encoding="utf-8"
    ):
        pass

    initialize_csv(
        MOVE_STATS_PATH,
        MOVE_STATS_FIELDS
    )

    initialize_csv(
        GAME_RESULTS_PATH,
        GAME_RESULTS_FIELDS
    )

    initialize_csv(
        SUMMARY_PATH,
        SUMMARY_FIELDS
    )


