def build_max_comment(row):
    """Build a readable PGN annotation for a Max move"""

    depth = (
        row["depth"]
        if row["depth"] is not None
        else "?"
    )

    score = row["score_cp_max"]

    score_text = (
        f"{score:+d}cp"
        if score is not None
        else "?"
    )

    return (
        f"MaxStats: "
        f"depth={depth}, "
        f"score={score_text}, "
        f"main_nodes={row['main_nodes']}, "
        f"qnodes={row['qnodes']}, "
        f"total_nodes={row['total_nodes']}, "
        f"nps={row['nps']}, "
        f"TT={row['tt_hits']}/{row['tt_probes']} "
        f"({row['tt_hit_rate_pct']:.1f}%), "
        f"cutoffs={row['beta_cutoffs']}, "
        f"qcutoffs={row['q_beta_cutoffs']}, "
        f"time={row['reported_time_s']:.3f}s"
    )


