def new_result_stats():
    """Create W-D-L counters for Max by color"""

    return {
        "white": {
            "wins": 0,
            "draws": 0,
            "losses": 0,
        },
        "black": {
            "wins": 0,
            "draws": 0,
            "losses": 0,
        },
    }


def update_result_stats(
    stats,
    result,
    max_plays_white
):
    """Update Max's W-D-L statistics"""

    color = (
        "white"
        if max_plays_white
        else "black"
    )

    if result == "1/2-1/2":

        stats[color]["draws"] += 1

    elif (
        result == "1-0"
        and max_plays_white
    ) or (
        result == "0-1"
        and not max_plays_white
    ):

        stats[color]["wins"] += 1

    else:

        stats[color]["losses"] += 1


def max_outcome(
    result,
    max_plays_white
):
    """Return Win/Draw/Loss from Max's perspective"""

    if result == "1/2-1/2":
        return "Draw"

    if (
        result == "1-0"
        and max_plays_white
    ) or (
        result == "0-1"
        and not max_plays_white
    ):
        return "Win"

    return "Loss"


